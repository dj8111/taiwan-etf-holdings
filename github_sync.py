"""
GitHub Data Synchronizer for Taiwan ETF Project
Fetches the latest database and CSV datasets generated by GitHub Actions.
"""

import os
import shutil
import tempfile
from datetime import datetime
from typing import Dict, Any, Optional
import requests

GITHUB_REPO = "dj8111/taiwan-etf-holdings"
GITHUB_BRANCH = "main"

RAW_BASE = f"https://raw.githubusercontent.com/{GITHUB_REPO}/{GITHUB_BRANCH}"
API_COMMIT_URL = f"https://api.github.com/repos/{GITHUB_REPO}/commits/{GITHUB_BRANCH}"

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE_DIR, "etf_data.db")
DATA_DIR = os.path.join(BASE_DIR, "data")
STATUS_FILE = os.path.join(BASE_DIR, ".github_sync_status.json")


def get_remote_commit_info() -> Dict[str, Any]:
    """
    從 GitHub API 取得 main 分支最新 Commit 資訊
    """
    try:
        resp = requests.get(
            API_COMMIT_URL,
            headers={"User-Agent": "Taiwan-ETF-App/1.0"},
            timeout=8
        )
        if resp.status_code == 200:
            data = resp.json()
            return {
                "success": True,
                "sha": data.get("sha", "")[:7],
                "full_sha": data.get("sha", ""),
                "message": data.get("commit", {}).get("message", "").split("\n")[0],
                "commit_date": data.get("commit", {}).get("committer", {}).get("date", ""),
            }
    except Exception as e:
        return {"success": False, "error": str(e)}
    return {"success": False, "error": f"HTTP {resp.status_code if 'resp' in locals() else 'Unknown'}"}


def get_sync_status() -> Dict[str, Any]:
    """
    讀取當前同步狀態
    """
    import json
    if os.path.exists(STATUS_FILE):
        try:
            with open(STATUS_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass

    return {
        "last_sync_time": None,
        "last_commit_sha": None,
        "last_commit_msg": None,
        "source": "GitHub Actions",
    }


def save_sync_status(info: Dict[str, Any]):
    """
    儲存同步狀態
    """
    import json
    try:
        with open(STATUS_FILE, "w", encoding="utf-8") as f:
            json.dump(info, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


def download_file(url: str, target_path: str, timeout: int = 40) -> bool:
    """
    下載遠端檔案覆蓋目標路徑
    """
    temp_dir = os.path.dirname(target_path)
    os.makedirs(temp_dir, exist_ok=True)
    temp_path = target_path + ".tmp"

    try:
        with requests.get(url, stream=True, timeout=timeout) as r:
            if r.status_code != 200:
                return False
            with open(temp_path, "wb") as f:
                for chunk in r.iter_content(chunk_size=131072):
                    if chunk:
                        f.write(chunk)
        
        # 成功下載後替換目標檔案
        if os.path.exists(target_path):
            try:
                os.remove(target_path)
            except Exception:
                pass
        
        shutil.move(temp_path, target_path)
        return True
    except Exception as e:
        print(f"[!] 下載 {url} 失敗: {e}")
        if os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except Exception:
                pass
        return False


def sync_from_github(dispose_callback=None, force: bool = False) -> Dict[str, Any]:
    """
    從 GitHub 遠端儲存庫同步最新 etf_data.db 與 CSV 報表
    """
    remote_info = get_remote_commit_info()
    current_status = get_sync_status()

    # 如果有回調函式，先釋放資料庫連線鎖定
    if dispose_callback:
        try:
            dispose_callback()
        except Exception as e:
            print(f"[!] 釋放 DB 連線例外: {e}")

    # 1. 下載 etf_data.db
    db_url = f"{RAW_BASE}/etf_data.db"
    db_success = download_file(db_url, DB_PATH, timeout=60)

    # 2. 下載主要 CSV 報表
    csv_files = [
        "data/etf_holdings_latest.csv",
        "data/etf_holdings_all_history.csv",
        "data/etf_navs_history.csv",
    ]
    csv_success_count = 0
    for rel_path in csv_files:
        url = f"{RAW_BASE}/{rel_path}"
        target = os.path.join(BASE_DIR, rel_path)
        if download_file(url, target, timeout=30):
            csv_success_count += 1

    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    sha = remote_info.get("sha") if remote_info.get("success") else current_status.get("last_commit_sha", "main")
    msg = remote_info.get("message") if remote_info.get("success") else "GitHub Sync"

    new_status = {
        "last_sync_time": now_str,
        "last_commit_sha": sha,
        "last_commit_msg": msg,
        "commit_date": remote_info.get("commit_date", ""),
        "source": "GitHub Actions",
        "db_synced": db_success,
        "csv_synced_count": csv_success_count,
    }
    save_sync_status(new_status)

    return {
        "updated": True,
        "success": db_success,
        "message": f"成功自 GitHub 同步資料庫 (版本: {sha})",
        "sha": sha,
        "commit_date": remote_info.get("commit_date", ""),
        "sync_time": now_str,
        "db_synced": db_success,
        "csv_synced_count": csv_success_count,
    }
